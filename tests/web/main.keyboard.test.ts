function node(
  hash: string,
  parentHashes: string[],
  extra: Partial<GitCommitNode> = {}
): GitCommitNode {
  return {
    hash,
    parentHashes,
    author: "a",
    email: "e",
    date: 1700000000,
    message: `m ${hash}`,
    refs: [],
    stash: null,
    ...extra
  };
}

function ref(hash: string, name: string, type: GitRef["type"]): GitRef {
  return { hash, name, type };
}

