/** Opens M's details and requests the history of its file; `entries` are the matching hashes. */
function requestFileHistory(entries: string[] | null): void {
  openDetails("M");
  const icon = document.querySelector<HTMLElement>("#commitDetails .highlightFileHistory");
  expect(icon, "file history icon").not.toBeNull();
  const before = posts().length;
  fire(icon!, "click");
  const [request] = posts("fileHistory");
  expect(request, "fileHistory request").toBeDefined();
  expect(posts().length - before).toBe(1);
  if (entries === null) return;
  dispatch({
    command: "fileHistory",
    repo: REPO,
    requestId: request!.requestId,
    anchorHash: "M",
    filePath: FILE_PATH,
    entries: entries.map((hash) => ({
      hash,
      parentHashes: [],
      type: "M",
      oldFilePath: FILE_PATH,
      newFilePath: FILE_PATH,
      historicalPath: FILE_PATH,
      isMerge: false
    }))
  });
  expect(historyIsActive()).toBe(true);
}

/** Answers a hard refresh: the branch response (whose callback requests commits) and the commits. */
function respondToRefresh(commits: GitCommitNode[], head: string | null = "M"): void {
  loadBranches();
  clearPosts();
  loadCommits(commits, { head });
}

/** Closes every layer a previous case may have left open. */
function closeEverything(): void {
  if (menuIsActive()) fire(document, "click");
  if (dialogIsActive()) pressEscape();
  for (const id of ["repoSelect", "branchSelect", "authorSelect"]) {
    if (dropdownIsOpen(id)) pressEscape();
  }
  if (findWidgetIsVisible()) fire(document.getElementById("findClose")!, "click");
  if (details() !== null) fire(document.getElementById("commitDetailsClose")!, "click");
  if (historyIsActive()) fire(document.getElementById("fileHistoryExit")!, "click");
  if (details() !== null) fire(document.getElementById("commitDetailsClose")!, "click");
  if (pathBar().classList.contains(CLASS_ACTIVE)) {
    fire(document.getElementById("pathHighlightClear")!, "click");
  }
  const panel = document.getElementById("branchCleanupPanel")!;
  if (!panel.hasAttribute("hidden")) fire(document.getElementById("branchCleanupBtn")!, "click");
  for (const extra of Array.from(document.querySelectorAll(".keyboardTestExtra"))) extra.remove();
}

