function dispatch(data: Record<string, unknown>): void {
  window.dispatchEvent(new MessageEvent("message", { data }));
}

function loadCommits(
  commits: GitCommitNode[],
  options: { head?: string | null; hard?: boolean; moreCommitsAvailable?: boolean } = {}
): void {
  dispatch({
    command: "loadCommits",
    commits,
    head: options.head === undefined ? "M" : options.head,
    moreCommitsAvailable: options.moreCommitsAvailable ?? false,
    hard: options.hard ?? true
  });
}

function loadBranches(): void {
  dispatch({
    command: "loadBranches",
    branches: ["feature", "hotfix"],
    head: "feature",
    hard: true,
    isRepo: true
  });
}

function loadRepos(repos: string[], lastActiveRepo = REPO): void {
  dispatch({
    command: "loadRepos",
    repos: Object.fromEntries(
      repos.map((repo) => [repo, { columnWidths: null, recentActions: [] }])
    ),
    lastActiveRepo
  });
}

function fire(target: Element | Document, type: string, init: MouseEventInit = {}): MouseEvent {
  const event = new MouseEvent(type, { bubbles: true, cancelable: true, ...init });
  target.dispatchEvent(event);
  return event;
}

interface KeyOptions extends KeyboardEventInit {
  readonly keyup?: boolean;
}

/** Dispatches keydown (and by default the matching keyup); returns the keydown event. */
function press(target: EventTarget, key: string, options: KeyOptions = {}): KeyboardEvent {
  const { keyup = true, ...init } = options;
  const keydown = new KeyboardEvent("keydown", { key, bubbles: true, cancelable: true, ...init });
  target.dispatchEvent(keydown);
  if (keyup) {
    target.dispatchEvent(
      new KeyboardEvent("keyup", { key, bubbles: true, cancelable: true, ...init })
    );
  }
  return keydown;
}

function pressEscape(target: EventTarget = document, init: KeyboardEventInit = {}): KeyboardEvent {
  return press(target, "Escape", { keyup: false, ...init });
}

function releaseEscape(target: EventTarget = document): void {
  target.dispatchEvent(
    new KeyboardEvent("keyup", { key: "Escape", bubbles: true, cancelable: true })
  );
}

