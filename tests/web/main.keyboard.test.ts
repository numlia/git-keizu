describe("Tab boundary between the target row's labels and the details (S73)", () => {
  function detailsStops(): HTMLElement[] {
    return Array.from(details()!.querySelectorAll<HTMLElement>("a[href]"));
  }

  beforeEach(() => {
    loadCommits(labelsOnLastRowCommits(), { head: "R" });
    openDetails("N");
    clearPosts();
  });

  it("goes from the last label of the target row into the details of another row (TC-702)", () => {
    // Case: TC-702 (K20)
    const [first, second] = labelsOf("R");
    const [firstDetailsStop] = detailsStops();
    expect(firstDetailsStop).toBeDefined();
    const target = focusRow("R");

    expect(press(target, "Tab").defaultPrevented).toBe(false);
    first.focus();
    expect(press(first, "Tab").defaultPrevented).toBe(false);
    second.focus();
    const boundary = press(second, "Tab");

    expect(boundary.defaultPrevented).toBe(true);
    expect(document.activeElement).toBe(firstDetailsStop);
  });

  it("returns from the first details control to the last label with Shift+Tab (TC-703)", () => {
    // Case: TC-703 (K20)
    focusRow("R");
    const [, second] = labelsOf("R");
    const [firstDetailsStop] = detailsStops();
    firstDetailsStop.focus();

    const boundary = press(firstDetailsStop, "Tab", { shiftKey: true });

    expect(boundary.defaultPrevented).toBe(true);
    expect(document.activeElement).toBe(second);
    expect(press(second, "Tab", { shiftKey: true }).defaultPrevented).toBe(false);
  });

  it("keeps labels of other rows out of the tab order (TC-704)", () => {
    // Case: TC-704
    loadCommits(standardCommits(), { head: "R" });
    for (const label of labelsOf("M"))
      expect(label.getAttribute("tabindex")).toBe(PROGRAMMATIC_ONLY);
    focusRow("R");
    press(row("R"), "ArrowUp");
    for (const label of labelsOf("M")) expect(label.getAttribute("tabindex")).toBe(TAB_STOP);
  });

  it("does not consume Tab at the end of the details or Shift+Tab on the row (TC-707)", () => {
    // Case: TC-707
    const stops = detailsStops();
    const last = stops[stops.length - 1];
    last.focus();
    expect(press(last, "Tab").defaultPrevented).toBe(false);
    expect(document.activeElement).toBe(last);

    const target = focusRow("R");
    expect(press(target, "Tab", { shiftKey: true }).defaultPrevented).toBe(false);
    expect(document.activeElement).toBe(target);
  });
});

